// Generates the CSS variables and the registry "tokens" item from tokens.json.
// Usage: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const source = JSON.parse(
  readFileSync(join(root, "registry/iq/tokens/tokens.json"), "utf8")
)

const vars = {}
for (const group of source.groups) {
  for (const token of group.tokens) vars[token.name] = token.value
}

// 1. registry/iq/styles/tokens.css — imported by the docs site.
const css = [
  "/* Generated by scripts/build-tokens.mjs from registry/iq/tokens/tokens.json. Do not edit. */",
  ":root {",
  "  color-scheme: dark;",
  ...source.groups.flatMap((group) => [
    `  /* ${group.name} */`,
    ...group.tokens.map((t) => `  --${t.name}: ${t.value};`),
  ]),
  "}",
  "",
].join("\n")

const cssPath = join(root, "registry/iq/styles/tokens.css")
mkdirSync(dirname(cssPath), { recursive: true })
writeFileSync(cssPath, css)

// 2. registry.json — the "tokens" item merges these into the consumer's :root.
// shadcn writes cssVars.light to :root; the IQ system is dark-only, so that is the only mode.
const registryPath = join(root, "registry.json")
const registry = JSON.parse(readFileSync(registryPath, "utf8"))
const item = registry.items.find((i) => i.name === "tokens")
if (!item) throw new Error('registry.json is missing the "tokens" item')
item.cssVars = { light: vars }
writeFileSync(registryPath, JSON.stringify(registry, null, 2) + "\n")

// 3. app/docs-theme.css — docs site only (never shipped in the registry).
// The docs chrome (header, menu, page, prose) can switch to light; the IQ system itself stays dark,
// so anything marked .ds-keep-dark (previews, matrices, token cards) re-declares the original values.
const LIGHT_SOLID = {
  "#0d100f": "#f5f6f6", "#121514": "#ffffff", "#141716": "#f0f1f1", "#191c1b": "#ebedec",
  "#1a1d1c": "#ebedec", "#1e2120": "#e3e5e4", "#252827": "#dcdfde", "#333635": "#c9cccb",
  "#0d221c": "#e3f7f0", "#ffffff": "#0d100f", "#a8a9a9": "#5e6362", "#12f0b4": "#00a276",
}
const toLight = (value) => {
  const m = String(value).trim().toLowerCase().match(/^(#[0-9a-f]{6})([0-9a-f]{2})?$/)
  if (!m) return null
  const [, base, alpha] = m
  if (alpha) return base === "#ffffff" ? `#0d100f${alpha}` : null // white overlays become ink overlays
  return LIGHT_SOLID[base] ?? null
}
const lightVars = Object.entries(vars).flatMap(([name, value]) => {
  const light = toLight(value)
  return light ? [`  --${name}: ${light};`] : []
})
const docsCss = [
  "/* Generated by scripts/build-tokens.mjs. Do not edit. Docs site only: light chrome, dark IQ content. */",
  'html[data-docs-theme="light"] {',
  "  color-scheme: light;",
  "  --docs-ink: #0d100f;",
  "  --color-white: #0d100f;",
  ...lightVars,
  "}",
  'html[data-docs-theme="light"] .ds-keep-dark {',
  "  color-scheme: dark;",
  "  --docs-ink: #ffffff;",
  "  --color-white: #ffffff;",
  ...Object.entries(vars).map(([name, value]) => `  --${name}: ${value};`),
  "}",
  "",
].join("\n")
writeFileSync(join(root, "app/docs-theme.css"), docsCss)

console.log(`✓ ${Object.keys(vars).length} tokens → tokens.css + registry.json + docs-theme.css (${lightVars.length} light overrides)`)
